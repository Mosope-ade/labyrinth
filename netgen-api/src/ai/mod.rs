// ─── ConversationEngine ───────────────────────────────────────────────────────

#[derive(Debug, Error)]
pub enum EngineError {
    #[error("AI call failed: {0}")]
    AiCall(String),
    #[error("Session not found: {0}")]
    SessionNotFound(Uuid),
}

/// Result of one conversation turn.
pub struct TurnResult {
    pub session_id: Uuid,
    pub reply: String,
    pub phase: DesignPhase,
    /// Set when the AI produced a validated NetworkIntent and the phase advanced to Building.
    pub intent: Option<ParsedIntent>,
    /// Set when both the primary parse and the retry failed — caller must show the form builder.
    pub fallback_required: bool,
    /// Industry detected from the accumulated conversation text, if any.
    pub detected_industry: Option<Industry>,
}

/// Drives the full Gathering → Building → Refining conversation lifecycle.
///
/// Holds sessions in memory (Phase 12 will back these with PostgreSQL).
pub struct ConversationEngine {
    client: AiClient,
    sessions: Arc<Mutex<HashMap<Uuid, ConversationState>>>,
}

impl ConversationEngine {
    pub fn new(client: AiClient) -> Self {
        Self {
            client,
            sessions: Arc::new(Mutex::new(HashMap::new())),
        }
    }

    /// Processes one user turn and returns the engine's result.
    ///
    /// - `session_id = None` → starts a new conversation.
    /// - `session_id = Some(id)` → continues an existing conversation.
    pub async fn turn(
        &self,
        session_id: Option<Uuid>,
        user_message: &str,
    ) -> Result<TurnResult, EngineError> {
        let sid = session_id.unwrap_or_else(Uuid::new_v4);

        // ── 1. Prepare: inject system prompt on first turn, add user message ──
        let (call_messages, current_phase, accumulated_text) = {
            let mut sessions = self.sessions.lock().await;

            // On new session: evict stale sessions, then enforce cap.
            if !sessions.contains_key(&sid) {
                let cutoff = Utc::now() - chrono::Duration::hours(SESSION_TTL_HOURS);
                sessions.retain(|_, s| s.updated_at >= cutoff);
                if sessions.len() >= MAX_SESSIONS {
                    return Err(EngineError::AiCall(
                        "server session capacity reached — try again later".into(),
                    ));
                }
            }

            let state = sessions.entry(sid).or_insert_with(ConversationState::new);

            if state.messages.is_empty() {
                state.push_message(ChatMessage::system(SYSTEM_PROMPT));
            }
            state.push_message(ChatMessage::user(user_message));

            let text = state.user_text();
            (state.messages.clone(), state.phase.clone(), text)
        };

        let detected_industry = detect_industry(&accumulated_text);

        // ── 2. Primary AI call (lock not held) ───────────────────────────────
        let response = self
            .client
            .complete(&call_messages)
            .await
            .map_err(|e| EngineError::AiCall(e.to_string()))?;

        // ── 3. During Gathering: try to extract an intent from the response ──
        if current_phase == DesignPhase::Gathering {
            match parse_intent(&response) {
                Ok(parsed) => {
                    let mut sessions = self.sessions.lock().await;
                    let state = sessions.get_mut(&sid).unwrap();
                    state.push_message(ChatMessage::assistant(response.clone()));
                    state.advance_phase(); // Gathering → Building
                    state.reset_retry();
                    return Ok(TurnResult {
                        session_id: sid,
                        reply: parsed.transition_message.clone(),
                        phase: DesignPhase::Building,
                        intent: Some(parsed),
                        fallback_required: false,
                        detected_industry,
                    });
                }

                Err(ParseError::NoJsonBlock) => {
                    // Normal conversational response — still gathering
                }

                Err(parse_err) => {
                    // Parse found JSON but it was invalid — one retry
                    let (should_retry, retry_messages) = {
                        let mut sessions = self.sessions.lock().await;
                        let state = sessions.get_mut(&sid).unwrap();
                        let can = !state.retry_exhausted();
                        state.push_message(ChatMessage::assistant(response.clone()));
                        if can {
                            state.increment_retry();
                            let mut msgs = state.messages.clone();
                            msgs.push(ChatMessage::user(format_retry_context(&parse_err)));
                            (true, msgs)
                        } else {
                            (false, vec![])
                        }
                    };

                    if should_retry {
                        let retry_response = self
                            .client
                            .complete(&retry_messages)
                            .await
                            .map_err(|e| EngineError::AiCall(e.to_string()))?;

                        let mut sessions = self.sessions.lock().await;
                        let state = sessions.get_mut(&sid).unwrap();

                        match parse_intent(&retry_response) {
                            Ok(parsed) => {
                                state.push_message(ChatMessage::assistant(retry_response.clone()));
                                state.advance_phase();
                                state.reset_retry();
                                return Ok(TurnResult {
                                    session_id: sid,
                                    reply: parsed.transition_message.clone(),
                                    phase: DesignPhase::Building,
                                    intent: Some(parsed),
                                    fallback_required: false,
                                    detected_industry,
                                });
                            }
                            Err(_) => {
                                state.push_message(ChatMessage::assistant(retry_response.clone()));
                                let phase = state.phase.clone();
                                return Ok(TurnResult {
                                    session_id: sid,
                                    reply: retry_response,
                                    phase,
                                    intent: None,
                                    fallback_required: true,
                                    detected_industry,
                                });
                            }
                        }
                    } else {
                        // Retry budget already exhausted
                        let sessions = self.sessions.lock().await;
                        let phase = sessions
                            .get(&sid)
                            .map(|s| s.phase.clone())
                            .unwrap_or(DesignPhase::Gathering);
                        return Ok(TurnResult {
                            session_id: sid,
                            reply: response,
                            phase,
                            intent: None,
                            fallback_required: true,
                            detected_industry,
                        });
                    }
                }
            }
        }

        // ── 4. Normal response (conversational or Refining delta) ─────────────
        let phase = {
            let mut sessions = self.sessions.lock().await;
            let state = sessions.get_mut(&sid).unwrap();
            state.push_message(ChatMessage::assistant(response.clone()));
            state.phase.clone()
        };

        Ok(TurnResult {
            session_id: sid,
            reply: response,
            phase,
            intent: None,
            fallback_required: false,
            detected_industry,
        })
    }

    /// Returns a snapshot of the current conversation state.
    pub async fn state(&self, session_id: Uuid) -> Option<ConversationState> {
        let sessions = self.sessions.lock().await;
        sessions.get(&session_id).cloned()
    }

    /// Returns all active session IDs.
    pub async fn active_sessions(&self) -> Vec<Uuid> {
        self.sessions.lock().await.keys().copied().collect()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn system_prompt_is_nonempty_and_covers_key_topics() {
        assert!(!SYSTEM_PROMPT.is_empty());
        assert!(SYSTEM_PROMPT.contains("Gathering"));
        assert!(SYSTEM_PROMPT.contains("Building"));
        assert!(SYSTEM_PROMPT.contains("Refining"));
        assert!(SYSTEM_PROMPT.contains("NEVER"));
        assert!(SYSTEM_PROMPT.contains("NetworkIntent"));
    }

    #[test]
    fn system_prompt_mentions_all_required_intent_fields() {
        for field in &["metadata", "topology", "routing", "segmentation", "addressing"] {
            assert!(
                SYSTEM_PROMPT.contains(field),
                "system prompt missing field: {field}"
            );
        }
    }

    // ConversationEngine unit tests use a mock AI — tested via conversation state directly
    #[test]
    fn turn_result_fields_are_accessible() {
        let result = TurnResult {
            session_id: Uuid::new_v4(),
            reply: "Hello".into(),
            phase: DesignPhase::Gathering,
            intent: None,
            fallback_required: false,
            detected_industry: Some(Industry::Healthcare),
        };
        assert_eq!(result.phase, DesignPhase::Gathering);
        assert!(!result.fallback_required);
        assert_eq!(result.detected_industry, Some(Industry::Healthcare));
    }

    #[test]
    fn engine_error_messages_are_descriptive() {
        let e = EngineError::AiCall("timeout".into());
        assert!(e.to_string().contains("timeout"));

        let id = Uuid::new_v4();
        let e2 = EngineError::SessionNotFound(id);
        assert!(e2.to_string().contains(&id.to_string()));
    }
}
